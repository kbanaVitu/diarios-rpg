export function t(keyPath, params = {}) {
  const parts = String(keyPath).split('.');
  let current = ptBR;
  for (const part of parts) {
    if (current && typeof current === 'object' && part in current) {
      current = current[part];
    } else {
      return keyPath;
    }
  }
  if (typeof current !== 'string') {
    return keyPath;
  }
  return current.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? params[k] : `{${k}}`));
}

export function formatRole(role) {
  return ptBR.roles[role] || role || 'Membro';
}

export function formatTableStatus(status) {
  return ptBR.status[status] || status || 'Ativa';
}

